#!/bin/sh
# Legt die Rollen des Forschungskerns an (läuft einmalig als Superuser beim ersten Start).
set -eu
psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" <<SQL
CREATE ROLE dart_owner LOGIN BYPASSRLS PASSWORD '${DART_OWNER_PASSWORD}';
CREATE ROLE dart_app LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOBYPASSRLS PASSWORD '${DART_APP_PASSWORD}';
CREATE ROLE dart_worker LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOBYPASSRLS PASSWORD '${DART_WORKER_PASSWORD}';
CREATE ROLE dart_migration LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOBYPASSRLS PASSWORD '${DART_MIGRATION_PASSWORD}';
CREATE DATABASE dart OWNER dart_owner;
REVOKE ALL ON DATABASE dart FROM PUBLIC;
GRANT CONNECT ON DATABASE dart TO dart_app, dart_worker, dart_migration;
SQL
